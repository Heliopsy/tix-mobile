// What the Licenses page lists.
//
//   dart run tool/licences.dart gen
//       write lib/src/core/licences/packages.g.dart from the package graph
//   dart run tool/licences.dart report NOTICES.Z
//       count a build's Flutter notices before and after filtering

import 'dart:convert';
import 'dart:io';

import 'package:tix_mobile/src/core/licences/notices.dart';
import 'package:tix_mobile/src/core/licences/packages.g.dart' as generated;

const _out = 'lib/src/core/licences/packages.g.dart';

Future<void> main(List<String> args) async {
  switch (args) {
    case ['gen']:
      await _gen();
    case ['report', final path]:
      _report(File(path));
    default:
      stderr.writeln('usage: dart run tool/licences.dart gen|report NOTICES.Z');
      exitCode = 64;
  }
}

Future<void> _gen() async {
  final r = await Process.run('dart', ['pub', 'deps', '--json']);
  if (r.exitCode != 0) {
    throw ProcessException('dart', ['pub', 'deps'], '${r.stderr}');
  }
  final doc = jsonDecode('${r.stdout}') as Map<String, Object?>;
  final packages = {
    for (final p in (doc['packages']! as List).cast<Map<String, Object?>>())
      p['name']! as String: p,
  };
  final root = packages.values.firstWhere((p) => p['kind'] == 'root');
  final runtime = <String>{};
  final queue = [...(root['directDependencies']! as List).cast<String>()];
  while (queue.isNotEmpty) {
    final name = queue.removeLast();
    if (!runtime.add(name)) continue;
    queue.addAll(
      (packages[name]?['dependencies'] as List? ?? []).cast<String>(),
    );
  }
  final devOnly = packages.keys.toSet().difference(runtime)
    ..remove(root['name']);
  String set(Iterable<String> names) =>
      (names.toList()..sort()).map((n) => "  '$n',\n").join();
  File(_out).writeAsStringSync('''
// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by `dart run tool/licences.dart gen` from `dart pub deps --json`.
// Do not edit; `just gen-check` fails while it is stale.

/// Packages the app is built from: the closure of `dependencies`.
const runtimePackages = <String>{
${set(runtime)}};

/// Packages only development needs, never shipped.
const devOnlyPackages = <String>{
${set(devOnly)}};
''');
  stderr.writeln(
    'wrote $_out: ${runtime.length} runtime, ${devOnly.length} dev-only',
  );
}

void _report(File noticesZ) {
  final bytes = noticesZ.readAsBytesSync();
  final raw = utf8.decode(gzip.decode(bytes));
  final all = parseFlutterNotices(raw);
  final kept = keepShipped(all, devOnly: generated.devOnlyPackages);
  int size(List<Notice> ns) =>
      ns.fold(0, (s, n) => s + n.text.length + n.packages.join('\n').length);
  stdout
    ..writeln('before: ${all.length} blocks, ${size(all)} bytes')
    ..writeln('after:  ${kept.length} blocks, ${size(kept)} bytes');
}
