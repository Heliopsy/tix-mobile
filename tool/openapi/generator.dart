// Turns tix's OpenAPI document into freezed models and a Dio client.
//
// tix generates its document from one Go registry, so it uses a small, regular
// subset of OpenAPI 3.1, and this generator covers exactly that subset and
// fails loudly on anything else:
//
// - Component schemas are objects with optional properties (no `required`
//   lists) or string enums. Nullability is a 3.1 type array with "null".
// - A listing answers `{items: [T], next_cursor}`, which becomes `Page<T>`.
// - Every failure is the shared error envelope, mapped once in TixTransport.
//
// Models fall in two groups. A schema reachable from a request body is an
// input: every field is nullable, so leaving one out sends nothing, which is
// what a PATCH needs. An input field whose description says null clears it
// is a `Patch<T>?` instead, kept out of toJson and added back by the class's
// generated `toBody()`, which the client sends; so such a class may only be a
// request body itself, never nested in another schema.
//
// Every other schema is a response: strings, numbers and booleans the server
// always writes default to their zero value, lists and maps to empty, and
// only what the document marks nullable is nullable.

import 'package:yaml/yaml.dart';

/// Schema names that would collide with the app's own classes, and what the
/// generated class is called instead.
const renames = {
  'Connection': 'LiveConnection',
  'Membership': 'TenantMembership',
  'Session': 'AuthSession',
};

/// Methods whose name from the operation id would be a Dart keyword.
const methodRenames = {'session.switch': 'switchTenant'};

/// Query parameters left out of the client: `format=csv` turns a JSON listing
/// into CSV, which the typed method could not decode.
const skippedQuery = {'format'};

const _header = '''
// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by `just gen` (tool/openapi.dart) from api/tix-openapi.yaml.
// Do not edit by hand.
// coverage:ignore-file
''';

const _keywords = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', //
  'default', 'do', 'else', 'enum', 'extends', 'false', 'final', 'finally',
  'for', 'if', 'in', 'is', 'new', 'null', 'rethrow', 'return', 'super',
  'switch', 'this', 'throw', 'true', 'try', 'var', 'void', 'while', 'with',
};

/// Members a freezed class already has, which a field cannot shadow.
const _classMembers = {
  'hashCode', 'runtimeType', 'toString', 'noSuchMethod', 'copyWith', 'toJson',
  // A field named override hides the @override annotation in the generated
  // part files, which then fail to resolve.
  'override',
};

/// Members every enum already has, which a value cannot shadow.
const _enumMembers = {
  'hashCode',
  'runtimeType',
  'toString',
  'noSuchMethod',
  'values',
  'index',
  'name',
  'value',
};

/// Generates `models.gen.dart` and `client.gen.dart` from [yamlText].
Map<String, String> generate(String yamlText) {
  final doc = _plain(loadYaml(yamlText))! as Map<String, Object?>;
  final g = _Generator(doc);
  return {'models.gen.dart': g.models(), 'client.gen.dart': g.client()};
}

Object? _plain(Object? node) => switch (node) {
  final YamlMap m => {
    for (final e in m.entries) e.key.toString(): _plain(e.value),
  },
  final YamlList l => [for (final e in l) _plain(e)],
  _ => node,
};

class _Generator {
  _Generator(this.doc)
    : schemas = Map.of(
        ((doc['components']! as Map)['schemas']! as Map)
            .cast<String, Map<String, Object?>>(),
      ) {
    _findInputs();
  }

  final Map<String, Object?> doc;
  final Map<String, Map<String, Object?>> schemas;
  final inputs = <String>{};

  /// Input schemas referenced from inside another schema, not only as a body.
  final nested = <String>{};

  /// The keys of each input schema's fields that a JSON null clears.
  final clearable = <String, List<String>>{};

  static final _clears = RegExp(
    r'\bnull\s+(clears|removes|unsets)\b',
    caseSensitive: false,
  );

  static const _methods = ['get', 'post', 'put', 'patch', 'delete'];

  Iterable<_Op> get operations sync* {
    final paths = (doc['paths']! as Map).cast<String, Map<String, Object?>>();
    for (final MapEntry(key: path, value: item) in paths.entries) {
      for (final m in _methods) {
        final op = item[m];
        if (op is Map<String, Object?>) yield _Op(path, m, op);
      }
    }
  }

  // ------------------------------------------------------------ schemas

  void _findInputs() {
    void visit(Object? schema, {required bool top}) {
      if (schema is! Map) return;
      final ref = schema[r'$ref'];
      if (ref is String) {
        final name = ref.split('/').last;
        if (!top) nested.add(name);
        if (inputs.add(name)) visit(schemas[name], top: true);
        return;
      }
      for (final key in ['items', 'additionalProperties']) {
        visit(schema[key], top: false);
      }
      for (final s in (schema['allOf'] as List?) ?? const []) {
        visit(s, top: false);
      }
      for (final s in ((schema['properties'] as Map?) ?? const {}).values) {
        visit(s, top: false);
      }
    }

    for (final op in operations) {
      final content = (op.raw['requestBody'] as Map?)?['content'] as Map?;
      for (final media in (content ?? const {}).values) {
        visit((media as Map)['schema'], top: true);
      }
    }

    for (final name in inputs) {
      final props = ((schemas[name]?['properties'] as Map?) ?? const {})
          .cast<String, Map<String, Object?>>();
      final keys = [
        for (final MapEntry(:key, :value) in props.entries)
          if (_clears.hasMatch(value['description'] as String? ?? '')) key,
      ]..sort();
      if (keys.isEmpty) continue;
      if (nested.contains(name)) {
        throw FormatException(
          '$name has fields a null clears (${keys.join(', ')}) but is nested '
          'in another schema, whose toJson would drop them',
        );
      }
      clearable[name] = keys;
    }
  }

  static String className(String schema) => renames[schema] ?? schema;

  bool isEnum(String name) => schemas[name]?['enum'] != null;

  static (List<String> types, bool nullable) _types(Map<String, Object?> s) {
    final t = s['type'];
    final list = switch (t) {
      null => <String>[],
      final String one => [one],
      final List<Object?> many => many.cast<String>(),
      _ => throw FormatException('unexpected type $t'),
    };
    final nullable = list.contains('null');
    return (
      [
        for (final x in list)
          if (x != 'null') x,
      ],
      nullable,
    );
  }

  String models() {
    final out = StringBuffer(_header)
      ..writeln()
      ..writeln("import 'package:freezed_annotation/freezed_annotation.dart';")
      ..writeln("import 'package:tix_mobile/src/data/api/json.dart';")
      ..writeln()
      ..writeln("part 'models.gen.freezed.dart';")
      ..writeln("part 'models.gen.g.dart';")
      ..writeln();
    final names = schemas.keys.toList()..sort();
    for (final name in names) {
      final s = schemas[name]!;
      if (s['enum'] != null) {
        _enum(out, name, s);
      } else {
        final (types, _) = _types(s);
        if (types.isNotEmpty && types.single != 'object') {
          throw FormatException('schema $name is ${s['type']}, not an object');
        }
        _class(out, name, s);
      }
    }
    return out.toString();
  }

  void _enum(StringBuffer out, String name, Map<String, Object?> s) {
    final values = (s['enum']! as List).cast<String>();
    _doc(out, s['description'] as String?, '');
    out.writeln('enum ${className(name)} {');
    final used = <String>{};
    for (final v in values) {
      var id = _identifier(v, _enumMembers);
      if (id.isEmpty) id = v == '*' ? 'all' : 'empty';
      while (!used.add(id)) {
        id = _suffixed(id);
      }
      out
        ..writeln('  @JsonValue(${_str(v)})')
        ..writeln('  $id(${_str(v)}),');
    }
    out
      ..writeln('  ;')
      ..writeln()
      ..writeln('  const ${className(name)}(this.value);')
      ..writeln()
      ..writeln('  /// The value on the wire.')
      ..writeln('  final String value;')
      ..writeln('}')
      ..writeln();
  }

  void _class(StringBuffer out, String name, Map<String, Object?> s) {
    final cls = className(name);
    final input = inputs.contains(name);
    final clears = clearable[name] ?? const <String>[];
    final patches = <String>[];
    final props = ((s['properties'] as Map?) ?? const {})
        .cast<String, Map<String, Object?>>();
    _doc(out, s['description'] as String?, '');
    out
      ..writeln('@freezed')
      ..writeln('abstract class $cls with _\$$cls {')
      ..writeln('  /// Creates a [$cls].');
    if (props.isEmpty) {
      out.writeln('  const factory $cls() = _$cls;');
    } else {
      out.writeln('  const factory $cls({');
      final keys = props.keys.toList()..sort();
      final used = <String>{};
      for (final key in keys) {
        final p = props[key]!;
        var field = _identifier(key, _classMembers);
        while (!used.add(field)) {
          field = _suffixed(field);
        }
        _doc(out, p['description'] as String?, '    ');
        if (clears.contains(key)) {
          final (type, encode) = _patch(p, '$name.$key');
          patches.add('if ($field case final p?) ${_str(key)}: $encode');
          out.writeln(
            '    @JsonKey(name: ${_str(key)}, includeFromJson: false, '
            'includeToJson: false) Patch<$type>? $field,',
          );
          continue;
        }
        final f = _field(p, input: input, where: '$name.$key');
        out.writeln(
          '    @JsonKey(name: ${_str(key)}${f.keyArgs}) '
          '${f.annotations}${f.type} $field,',
        );
      }
      out.writeln('  }) = _$cls;');
    }
    out
      ..writeln()
      ..writeln('  /// Reads a [$cls] from its JSON object.')
      ..writeln(
        '  factory $cls.fromJson(Map<String, dynamic> json) => '
        '_\$${cls}FromJson(json);',
      )
      ..writeln('}')
      ..writeln();
    if (patches.isEmpty) return;
    out
      ..writeln('/// The request body of a [$cls], cleared fields included.')
      ..writeln('extension ${cls}Body on $cls {')
      ..writeln('  /// [$cls.toJson] plus every [Patch] field that is set.')
      ..writeln('  Map<String, dynamic> toBody() => {')
      ..writeln('    ...toJson(),');
    for (final p in patches) {
      out.writeln('    $p,');
    }
    out
      ..writeln('  };')
      ..writeln('}')
      ..writeln();
  }

  /// The type a clearable field wraps in a `Patch`, and the expression that
  /// encodes the `Patch` held in `p`.
  (String, String) _patch(Map<String, Object?> p, String where) {
    final ref = p[r'$ref'] as String?;
    if (ref != null) {
      final target = ref.split('/').last;
      return isEnum(target)
          ? (className(target), 'p.encode((v) => v.value)')
          : (className(target), 'p.encode((v) => v.toJson())');
    }
    final (types, _) = _types(p);
    switch (types.singleOrNull) {
      case 'string' when p['format'] == 'date-time':
        return ('DateTime', 'p.encode(const TixDateTime().toJson)');
      case 'string':
        return ('String', 'p.value');
      case 'boolean':
        return ('bool', 'p.value');
      case 'integer':
        return ('int', 'p.value');
      case 'number':
        return ('double', 'p.value');
    }
    throw FormatException('$where: a clearable ${p['type']} is not supported');
  }

  _Field _field(
    Map<String, Object?> p, {
    required bool input,
    required String where,
  }) {
    final ref = p[r'$ref'] as String?;
    if (ref != null) {
      final target = ref.split('/').last;
      if (isEnum(target)) {
        return _Field(
          '${className(target)}?',
          keyArgs: ', unknownEnumValue: JsonKey.nullForUndefinedEnumValue',
        );
      }
      return _Field('${className(target)}?');
    }
    final (types, nullable) = _types(p);
    if (types.isEmpty) return const _Field('Object?');
    if (types.length != 1) throw FormatException('$where: types $types');
    final opt = input || nullable;
    switch (types.single) {
      case 'string':
        if (p['format'] == 'date-time') {
          return const _Field('DateTime?', annotations: '@TixDateTime() ');
        }
        return opt
            ? const _Field('String?')
            : const _Field('String', annotations: "@Default('') ");
      case 'boolean':
        return opt
            ? const _Field('bool?')
            : const _Field('bool', annotations: '@Default(false) ');
      case 'integer':
        return opt
            ? const _Field('int?')
            : const _Field('int', annotations: '@Default(0) ');
      case 'number':
        return opt
            ? const _Field('double?')
            : const _Field('double', annotations: '@Default(0.0) ');
      case 'array':
        final item = _element(p['items'], where);
        return input
            ? _Field('List<$item>?')
            : _Field('List<$item>', annotations: '@Default(<$item>[]) ');
      case 'object':
        final ap = p['additionalProperties'];
        if (ap == null) throw FormatException('$where: object without a map');
        final value = ap is Map && ap.isEmpty ? 'Object?' : _element(ap, where);
        return input
            ? _Field('Map<String, $value>?')
            : _Field(
                'Map<String, $value>',
                annotations: '@Default(<String, $value>{}) ',
              );
    }
    throw FormatException('$where: type ${types.single}');
  }

  String _element(Object? schema, String where) {
    if (schema is! Map<String, Object?>) throw FormatException(where);
    final ref = schema[r'$ref'] as String?;
    if (ref != null) {
      final target = ref.split('/').last;
      // A newer server may add an enum value; inside a list there is no
      // field to fall back to null, so the raw string is kept.
      return isEnum(target) ? 'String' : className(target);
    }
    final (types, _) = _types(schema);
    return switch (types.singleOrNull) {
      'string' => 'String',
      'integer' => 'int',
      'boolean' => 'bool',
      'number' => 'double',
      'array' => 'List<${_element(schema['items'], where)}>',
      'object' => 'Map<String, Object?>',
      null => 'Object?',
      final t => throw FormatException('$where: element type $t'),
    };
  }

  // ------------------------------------------------------------- client

  String client() {
    final groups = <String, List<_Op>>{};
    for (final op in operations) {
      groups.putIfAbsent(op.group, () => []).add(op);
    }
    final names = groups.keys.toList()..sort();
    final out = StringBuffer(_header)
      ..writeln()
      ..writeln("import 'dart:typed_data';")
      ..writeln()
      ..writeln("import 'package:tix_mobile/src/data/api/gen/models.gen.dart';")
      ..writeln("import 'package:tix_mobile/src/data/api/transport.dart';")
      ..writeln("import 'package:tix_mobile/src/data/models/page.dart';")
      ..writeln()
      ..writeln('/// Every operation of the tix HTTP API, grouped by area.')
      ..writeln('class TixClient {')
      ..writeln('  /// Sends every request through [transport].')
      ..writeln('  TixClient(this.transport);')
      ..writeln()
      ..writeln('  /// The connection every request goes through.')
      ..writeln('  final TixTransport transport;')
      ..writeln();
    for (final g in names) {
      out
        ..writeln('  /// The `$g` operations.')
        ..writeln(
          '  late final ${_lowerCamel(g)} = ${_upperCamel(g)}Ops(transport);',
        );
    }
    out
      ..writeln('}')
      ..writeln();
    for (final g in names) {
      final ops = groups[g]!..sort((a, b) => a.id.compareTo(b.id));
      out
        ..writeln('/// The `$g` operations.')
        ..writeln('class ${_upperCamel(g)}Ops {')
        ..writeln('  /// Sends through [_t].')
        ..writeln('  const ${_upperCamel(g)}Ops(this._t);')
        ..writeln()
        ..writeln('  final TixTransport _t;');
      for (final op in ops) {
        _method(out, op);
        if (op.method == 'get' && _isPage(op) && _ndjson(op) != null) {
          _method(out, op, stream: true);
        }
        if (_isMultiMedia(op)) _method(out, op, file: true);
      }
      out
        ..writeln('}')
        ..writeln();
    }
    return out.toString();
  }

  Map<String, Object?>? _success(_Op op) {
    final responses = (op.raw['responses']! as Map).cast<String, Object?>();
    for (final code in responses.keys.toList()..sort()) {
      if (code.startsWith('2')) {
        final r = responses[code]! as Map<String, Object?>;
        if (r['content'] != null) return r;
      }
    }
    return null;
  }

  bool _hasNoContent(_Op op) =>
      (op.raw['responses']! as Map).containsKey('204');

  Map<String, Object?>? _json(_Op op) =>
      ((_success(op)?['content'] as Map?)?['application/json'] as Map?)
          ?.cast<String, Object?>();

  Map<String, Object?>? _ndjson(_Op op) =>
      ((_success(op)?['content'] as Map?)?['application/x-ndjson'] as Map?)
          ?.cast<String, Object?>();

  bool _isPage(_Op op) {
    final s = _json(op)?['schema'] as Map?;
    final props = s?['properties'] as Map?;
    return props != null &&
        props.containsKey('items') &&
        props.containsKey('next_cursor');
  }

  String _pageItem(_Op op) => _element(
    (((_json(op)!['schema']! as Map)['properties']! as Map)['items']!
        as Map)['items'],
    op.id,
  );

  /// Whether [op] answers JSON or a document format its request picks (CSV,
  /// Markdown), and takes no raw body: such an operation gets a `…File` twin
  /// returning the bytes as the server wrote them. A listing that also
  /// streams NDJSON is not one; it has its `…Stream` twin.
  bool _isMultiMedia(_Op op) {
    final content = (_success(op)?['content'] as Map?)?.keys ?? const [];
    return content.length > 1 &&
        content.any(
          (m) => m != 'application/json' && m != 'application/x-ndjson',
        ) &&
        _body(op)?.raw == null;
  }

  void _method(
    StringBuffer out,
    _Op op, {
    bool stream = false,
    bool file = false,
  }) {
    final params = (op.raw['parameters'] as List? ?? const [])
        .cast<Map<String, Object?>>();
    final pathParams = [
      for (final p in params)
        if (p['in'] == 'path') p,
    ];
    final query = [
      for (final p in params)
        if (p['in'] == 'query' &&
            !skippedQuery.contains(p['name']) &&
            !(stream && p['name'] == 'cursor'))
          p,
    ];
    final prefixes =
        (op.raw['x-tix-query-prefixes'] as List?)?.cast<String>() ?? const [];

    final sig = <String>[];
    final named = <String>[];
    for (final p in pathParams) {
      sig.add('String ${_identifier(p['name']! as String)}');
    }
    final body = _body(op);
    if (body != null) {
      if (body.required) {
        sig.add('${body.type} body');
      } else {
        named.add('${body.type}? body');
      }
    }
    for (final p in query) {
      final type = _queryType(p['schema']! as Map<String, Object?>, op.id);
      named.add('$type? ${_identifier(p['name']! as String)}');
    }
    for (final prefix in prefixes) {
      named.add('Map<String, String>? ${_prefixParam(prefix)}');
    }

    final ret = file ? 'Future<Uint8List>' : _returnType(op, stream: stream);
    final name = stream
        ? '${op.member}Stream'
        : file
        ? '${op.member}File'
        : op.member;

    out.writeln();
    final summary = op.raw['summary'] as String? ?? '';
    _doc(out, summary.isEmpty ? null : '$summary.', '  ');
    final scopes = op.scopes;
    out
      ..writeln('  ///')
      ..writeln(
        '  /// `${op.method.toUpperCase()} ${op.path}` (`${op.id}`)'
        '${stream ? ' as NDJSON, one item per line' : ''}'
        '${file ? ' as the bytes of the format the request asks for' : ''}'
        '${scopes.isEmpty ? '' : ', scope ${_scopes(scopes)}'}.',
      );
    final args = [
      ...sig,
      if (named.isNotEmpty) '{${named.join(', ')},}',
    ].join(', ');
    out.write('  $ret $name($args)');

    final pathExpr = op.path.replaceAllMapped(
      RegExp(r'\{([^}]+)\}'),
      (m) => '\${_t.segment(${_identifier(m[1]!)})}',
    );
    final queryEntries = [
      for (final p in query)
        "${_str(p['name']! as String)}: ${_identifier(p['name']! as String)}",
      for (final prefix in prefixes) _prefixEntries(prefix),
    ];
    final q = queryEntries.isEmpty
        ? ''
        : ', query: {${queryEntries.join(', ')}}';
    final m = _str(op.method.toUpperCase());
    final b = body == null
        ? ''
        : body.raw != null
        ? ', body: body, contentType: ${_str(body.raw!)}'
        : ', body: body${body.required ? '' : '?'}.'
              '${clearable.containsKey(body.schema) ? 'toBody' : 'toJson'}()';
    final call = "$m, '$pathExpr'$q$b";

    if (stream) {
      final item = _pageItem(op);
      out.writeln(" => _t.ndjson($m, '$pathExpr'$q).map(${_decoder(item)});");
      return;
    }
    out
      ..writeln(' async {')
      ..writeln('    ${file ? 'return _t.bytes($call);' : _bodyFor(op, call)}')
      ..writeln('  }');
  }

  String _bodyFor(_Op op, String call) {
    final json = _json(op);
    final success = _success(op);
    if (success == null) return 'await _t.empty($call);';
    if (json == null) {
      final content = (success['content']! as Map).keys.first as String;
      if (content.startsWith('image/')) {
        return 'return _t.bytes($call);';
      }
      return 'return _t.text($call, accept: ${_str(content)});';
    }
    final schema = json['schema']! as Map<String, Object?>;
    if (_isPage(op)) {
      return 'return Page.fromJson(await _t.json($call), '
          '${_decoder(_pageItem(op))});';
    }
    final ref = schema[r'$ref'] as String?;
    if (ref != null) {
      final cls = className(ref.split('/').last);
      if (_hasNoContent(op)) {
        return 'final json = await _t.jsonOrNull($call);\n'
            '    return json == null ? null : $cls.fromJson(json);';
      }
      return 'return $cls.fromJson(await _t.json($call));';
    }
    final (types, _) = _types(schema);
    if (types.contains('array')) {
      return 'return _t.jsonList($call);';
    }
    return 'return _t.json($call);';
  }

  String _returnType(_Op op, {required bool stream}) {
    if (stream) return 'Stream<${_pageItem(op)}>';
    final success = _success(op);
    if (success == null) return 'Future<void>';
    final json = _json(op);
    if (json == null) {
      final content = (success['content']! as Map).keys.first as String;
      return content.startsWith('image/')
          ? 'Future<Uint8List>'
          : 'Future<String>';
    }
    if (_isPage(op)) return 'Future<Page<${_pageItem(op)}>>';
    final schema = json['schema']! as Map<String, Object?>;
    final ref = schema[r'$ref'] as String?;
    if (ref != null) {
      final cls = className(ref.split('/').last);
      return _hasNoContent(op) ? 'Future<$cls?>' : 'Future<$cls>';
    }
    final (types, _) = _types(schema);
    if (types.contains('array')) return 'Future<List<Object?>>';
    return 'Future<Map<String, dynamic>>';
  }

  static String _decoder(String item) => switch (item) {
    'String' || 'int' || 'bool' || 'double' => '(e) => e! as $item',
    'Object?' => '(e) => e',
    _ => '(e) => $item.fromJson(e! as Map<String, dynamic>)',
  };

  _Body? _body(_Op op) {
    final rb = op.raw['requestBody'] as Map?;
    if (rb == null) return null;
    final required = rb['required'] == true;
    final content = (rb['content']! as Map)
        .cast<String, Map<String, Object?>>();
    final json = content['application/json'];
    if (json != null) {
      final ref = (json['schema']! as Map)[r'$ref'] as String?;
      if (ref == null) throw FormatException('${op.id}: inline JSON body');
      final schema = ref.split('/').last;
      return _Body(className(schema), required: required, schema: schema);
    }
    final MapEntry(key: media, value: m) = content.entries.single;
    if ((m['schema']! as Map)['type'] != 'string') {
      throw FormatException('${op.id}: $media body is not a string');
    }
    return _Body('String', required: required, raw: media);
  }

  String _queryType(Map<String, Object?> s, String where) {
    final (types, _) = _types(s);
    return switch (types.single) {
      'string' => s['format'] == 'date-time' ? 'DateTime' : 'String',
      'integer' => 'int',
      'boolean' => 'bool',
      'number' => 'double',
      'array' => 'List<${_element(s['items'], where)}>',
      final t => throw FormatException('$where: query type $t'),
    };
  }

  static String _prefixParam(String prefix) =>
      '${_identifier(prefix.replaceAll('.', ''))}Filters';

  // ------------------------------------------------------------ helpers

  static void _doc(StringBuffer out, String? text, String indent) {
    if (text == null || text.trim().isEmpty) return;
    for (final para in text.trim().split('\n')) {
      final words = para.trim().split(RegExp(r'\s+'));
      var line = StringBuffer();
      for (final w in words) {
        if (line.length + w.length + 1 > 76 && line.isNotEmpty) {
          out.writeln('$indent/// $line'.trimRight());
          line = StringBuffer();
        }
        if (line.isNotEmpty) line.write(' ');
        line.write(w);
      }
      out.writeln('$indent/// $line'.trimRight());
    }
  }
}

class _Op {
  _Op(this.path, this.method, this.raw) : id = raw['operationId']! as String;

  final String path;
  final String method;
  final Map<String, Object?> raw;
  final String id;

  String get group => id.split('.').first;

  String get member {
    final renamed = methodRenames[id];
    if (renamed != null) return renamed;
    final rest = id.split('.').skip(1).join('_');
    return _identifier(rest);
  }

  List<String> get scopes {
    final out = <String>{};
    for (final req in (raw['security'] as List?) ?? const []) {
      for (final scopes in (req as Map).values) {
        out.addAll((scopes as List).cast<String>());
      }
    }
    return out.toList();
  }
}

