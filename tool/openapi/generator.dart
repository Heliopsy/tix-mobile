String _str(String s) {
  final escaped = s
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$');
  return "'$escaped'";
}

String _suffixed(String id) => '${id}_';

String _scopes(List<String> scopes) => scopes.map((s) => '`$s`').join(' or ');

/// The query entries a prefixed parameter map spreads into.
String _prefixEntries(String prefix) {
  final p = _Generator._prefixParam(prefix);
  return 'if ($p != null) for (final e in $p.entries) '
      "'$prefix\${e.key}': e.value";
}

/// A lowerCamel identifier from a wire name: `assignee_actor_id`,
/// `delete-plan`, `task:read`, `actorID`. A name taken by [avoid] or a Dart
/// keyword gets `Value` appended.
String _identifier(String wire, [Set<String> avoid = const {}]) {
  final words = [
    for (final part in wire.split(RegExp('[^A-Za-z0-9]+')))
      for (final m in RegExp(
        '[A-Z]+(?![a-z])|[A-Z]?[a-z0-9]+',
      ).allMatches(part))
        m[0]!.toLowerCase(),
  ];
  if (words.isEmpty) return '';
  final buf = StringBuffer(words.first);
  for (final w in words.skip(1)) {
    buf.write(w[0].toUpperCase() + w.substring(1));
  }
  var id = buf.toString();
  if (RegExp('^[0-9]').hasMatch(id)) id = 'v$id';
  return _keywords.contains(id) || avoid.contains(id) ? '${id}Value' : id;
}

String _lowerCamel(String s) => _identifier(s);

String _upperCamel(String s) {
  final id = _identifier(s);
  return id[0].toUpperCase() + id.substring(1);
}
